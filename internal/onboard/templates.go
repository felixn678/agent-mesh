package onboard

import (
	"fmt"
	"path/filepath"
)

// hubTOML is the generated hub.toml. Tokens appear only as hashes.
func hubTOML(listen, adminHash, host, hostHash, sessionHash string) string {
	return fmt.Sprintf(`# Generated by "agent-mesh up" (mode 0600). Tokens are stored as sha256 hashes only.
# Loopback by default. To serve other machines set listen to your Tailscale IP
# (e.g. "100.x.y.z:8787"); never bind 0.0.0.0 or a LAN/public address.
listen = %q
db_path = "~/.local/share/agent-mesh/hub.db"
admin_token_hash = %q

lease_ttl = "5m"
reap_interval = "60s"
stale_requeue = "1h"
revive_window = "30m"
session_alive_window = "12h"
retention = "168h"

# Daemons: lease + load + reads. "agent-mesh invite <name>" appends entries.
[host_tokens]
%q = %q

# Interactive Claude sessions: messaging, task add, reads.
[session_tokens]
%q = %q
`, listen, adminHash, host, hostHash, host, sessionHash)
}

// daemonTOML is daemon.toml with the safe defaults of the shipped examples.
// The repo allowlist starts empty: the user adds repos they trust.
func daemonTOML(hubURL, tokenFile, stateDir string) string {
	return fmt.Sprintf(`# Generated by "agent-mesh up|join" (mode 0600).
hub_url = %q
host_token_file = %q
state_dir = %q   # repos/ worktrees/ logs/ spool/ run/

poll_interval = "30s"
heartbeat_interval = "60s"
task_timeout = "3h"
git_call_timeout = "120s"                 # keep below hub lease_ttl / 2

max_cpu_pct = 80
min_mem_avail_pct = 25
max_agent_worktrees = 2
stuck_retention = "72h"
log_retention = "168h"

allowed_permission_modes = ["acceptEdits", "dontAsk"]   # bypassPermissions/auto refuse to start
max_budget_usd_cap = 5.0
worker_setting_sources = "project"
claude_bin = "claude"
claude_env_file = ""                      # optional 0600 file: CLAUDE_CODE_OAUTH_TOKEN=...
gh_env_file = %q   # 0600: GH_TOKEN=<fine-grained PAT>
gitleaks_bin = "gitleaks"

# Allowlist: repo key -> remote URL the daemon clones. Use the canonical key
# "github.com/<user>/<repo>": tasks added from Claude sessions carry it.
[repos]
# "github.com/<user>/<repo>" = "https://github.com/<user>/<repo>.git"

# Default: read, edit and commit only. Workers run no repo code, so this is
# safe for any repo (tasks that name no profile use it).
[tool_profiles.default]
allow = ["Read", "Edit", "Write", "Glob", "Grep",
         "Bash(git status*)", "Bash(git diff*)", "Bash(git log*)",
         "Bash(git add *)", "Bash(git commit *)"]

# with-tests RUNS REPO CODE AS YOUR USER: tests and builds execute whatever the
# repo (or the agent) wrote, outside the worker's deny list, with access to
# your files and tokens. Only for repos you trust; tasks opt in with
# --profile with-tests. Adjust the commands to the repo's toolchain.
[tool_profiles.with-tests]
allow = ["Read", "Edit", "Write", "Glob", "Grep",
         "Bash(git status*)", "Bash(git diff*)", "Bash(git log*)",
         "Bash(git add *)", "Bash(git commit *)",
         "Bash(go test *)", "Bash(go build *)", "Bash(go vet *)"]
# allow_ssh_agent = true   # pass SSH_AUTH_SOCK (e.g. private modules over ssh); off by default
`, hubURL, tokenFile, stateDir, filepath.Join(filepath.Dir(tokenFile), "gh.env"))
}

// clientTOML tells CLI commands which hub to talk to.
func clientTOML(hubURL string) string {
	return fmt.Sprintf("# Generated by \"agent-mesh up|join\" (mode 0600).\nhub_url = %q\n", hubURL)
}
